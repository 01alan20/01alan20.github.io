import fs from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
import assert from 'node:assert/strict';
const {chromium}=await import(pathToFileURL(process.argv[2]).href);
const browser=await chromium.launch({channel:'chrome',headless:true});
const out='output/playwright/living-university';await fs.mkdir(out,{recursive:true});
const errors=[],requests=[];
const page=await browser.newPage({viewport:{width:1440,height:1000},colorScheme:'dark'});
page.on('pageerror',e=>errors.push(e.message));
page.on('request',r=>requests.push(r.url()));
await page.goto('http://127.0.0.1:8765/index.html');
await page.getByRole('link',{name:'Projects',exact:true}).click();
const card=page.locator('.featured-projects-grid .project-card').first();
assert.match(await card.innerText(),/The Living University/);
const [story]=await Promise.all([page.waitForEvent('popup'),card.click()]);
story.on('pageerror',e=>errors.push(e.message));story.on('request',r=>requests.push(r.url()));
await story.waitForSelector('.chapter');await story.emulateMedia({colorScheme:'dark'});
await story.screenshot({path:out+'/scroll-hero.png'});
assert.equal(await story.locator('canvas,audio,video,.controls').count(),0);
assert.equal(await story.locator('.state-tile').count(),51);
assert.equal(await story.locator('.annual-point').count(),30);
assert.equal(await story.locator('.cohort-dot').count(),100);
for(const id of ['demand','geography','institutions','completion','connections','value']){
  const section=story.locator('#'+id);
  await section.evaluate(el=>window.scrollTo({top:el.offsetTop,behavior:'instant'}));await story.waitForTimeout(400);
  const initial=Number(await section.getAttribute('data-progress'));
  await section.evaluate(el=>window.scrollTo({top:el.offsetTop+el.offsetHeight-innerHeight*.9,behavior:'instant'}));await story.waitForTimeout(700);
  const final=Number(await section.getAttribute('data-progress'));assert(final>initial+.2,`${id} did not animate: ${initial} -> ${final}`);
  await story.screenshot({path:out+'/scroll-'+id+'.png'});
  assert.equal(await story.locator('.chapter-nav [aria-current]').getAttribute('href'),'#'+id);
}
await story.setViewportSize({width:390,height:844});
await story.goto('http://127.0.0.1:8765/projects/living-university-motion/');
await story.locator('#completion').evaluate(el=>window.scrollTo({top:el.offsetTop+400,behavior:'instant'}));await story.waitForTimeout(500);
await story.screenshot({path:out+'/scroll-mobile.png'});
assert(await story.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile overflow');
await story.emulateMedia({reducedMotion:'reduce',colorScheme:'light'});await story.waitForTimeout(200);
assert.equal(await story.locator('.bar-end').first().evaluate(el=>getComputedStyle(el).transform),'matrix(1, 0, 0, 1, 0, 0)');
await story.locator('#demand').evaluate(el=>window.scrollTo({top:el.offsetTop,behavior:'instant'}));await story.waitForTimeout(200);
await story.screenshot({path:out+'/scroll-mobile-light-reduced.png'});
assert(!requests.some(u=>/\.(mp3|mp4|wav)(\?|$)/.test(u)),'Unexpected media request');
assert.deepEqual(errors,[]);
console.log(JSON.stringify({featuredCard:true,scrollChapters:6,annualObservations:30,stateTiles:51,cohortDots:100,mobileOverflow:false,reducedMotion:true,videoPlayer:false,errors},null,2));
await browser.close();
