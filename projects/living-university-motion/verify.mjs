import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath,pathToFileURL} from 'node:url';
const root=path.dirname(fileURLToPath(import.meta.url));
const {chromium}=await import(process.argv[2]?pathToFileURL(process.argv[2]).href:'playwright');
const browser=await chromium.launch({channel:'chrome',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[],failed=[];page.on('pageerror',e=>errors.push(e.message));page.on('response',r=>{if(r.status()>=400)failed.push(r.url()+': '+r.status());});
const base='http://127.0.0.1:8765';
await page.goto(base+'/index.html');
await page.getByRole('link',{name:'Projects',exact:true}).click();
const card=page.locator('.featured-projects-grid .project-card').first();
if(!await card.innerText().then(t=>t.includes('The Living University')))throw Error('New story is not first featured card');
const [storyPage]=await Promise.all([page.waitForEvent('popup'),card.click()]);
storyPage.on('pageerror',e=>errors.push(e.message));
await storyPage.waitForLoadState();
console.log('Card destination:',storyPage.url());
await storyPage.waitForFunction(()=>Boolean(window.livingPlayer));
await storyPage.getByRole('button',{name:/Watch the story/}).click();
await storyPage.waitForTimeout(2400);
const playback=await storyPage.evaluate(()=>window.livingPlayer.state);
if(!playback.playing||playback.time<1||playback.audioReady<2||playback.audioPaused)throw Error('Narrated playback failed '+JSON.stringify(playback));
await storyPage.getByRole('button',{name:'Pause story',exact:true}).click();
const paused=await storyPage.evaluate(()=>window.livingPlayer.state.time);await storyPage.waitForTimeout(350);
if(Math.abs(paused-await storyPage.evaluate(()=>window.livingPlayer.state.time))>.01)throw Error('Pause did not freeze time');
await storyPage.getByRole('button',{name:'Mute narration',exact:true}).click();
if(!await storyPage.evaluate(()=>window.livingPlayer.state.muted))throw Error('Mute failed');
const out=path.resolve(root,'../../output/playwright/living-university');await fs.mkdir(out,{recursive:true});
const frames=await storyPage.evaluate(()=>window.LivingStory.data.scenes.map(s=>({id:s.id,time:s.start+Math.min(10,s.duration*.7)})));
for(const f of frames){await storyPage.evaluate(t=>window.livingPlayer.seek(t),f.time);await storyPage.locator('canvas').screenshot({path:path.join(out,f.id+'.png')});}
await storyPage.getByRole('button',{name:/07.*Designing the future/}).click();
if(!(await storyPage.locator('#current-title').textContent()).includes('Build a university'))throw Error('Chapter navigation failed');
await storyPage.evaluate(()=>window.livingPlayer.seek(window.LivingStory.data.scenes[9].start+12));
await storyPage.screenshot({path:path.join(out,'desktop-player.png'),fullPage:true});
await storyPage.setViewportSize({width:390,height:844});
await storyPage.screenshot({path:path.join(out,'mobile-player.png'),fullPage:true});
const overflow=await storyPage.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
if(overflow)throw Error('Mobile horizontal overflow');
const audioFiles=await storyPage.evaluate(async()=>Promise.all(window.LivingStory.data.scenes.map(async s=>{const r=await fetch(s.audio);return {id:s.id,status:r.status,size:(await r.arrayBuffer()).byteLength};})));
if(audioFiles.some(x=>x.status!==200||x.size<1000))throw Error('Missing narration assets');
if(errors.length||failed.length)throw Error(JSON.stringify({errors,failed}));
console.log(JSON.stringify({passed:true,scenes:frames.length,playback,allNarrationFiles:true,mobileOverflow:overflow,screenshots:out},null,2));
await browser.close();
